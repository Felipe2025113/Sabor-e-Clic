const {test} = require('node:test')
const assert = require('node:assert/strict')
const {readFileSync} = require('node:fs')
const {runInNewContext} = require('node:vm')
const {join} = require('node:path')
const source = readFileSync(join(__dirname, '../static/js/models.js'), 'utf8')
const classes = runInNewContext(source + '\n({Usuario, Cliente, Administrador, Cozinheiro, Prato, ItemPedido, Carrinho, Pedido, CadastroCliente, Login})')
const {Usuario, Cliente, Administrador, Cozinheiro, Prato, ItemPedido, Carrinho, Pedido, CadastroCliente, Login} = classes
const prato = () => new Prato({id:1,nome:'Prato Teste',descricao:'Descrição teste',preco:19.90,categoria:'Testes'})
test('herança, campos privados e roundtrip JSON', () => {
 const c = new Cliente(1,'Ana Teste','ana@example.com','Rua Teste 123')
 assert.ok(c instanceof Usuario)
 assert.equal(Object.keys(c).length, 0)
 assert.equal(Usuario.deJSON(JSON.parse(JSON.stringify(c))).endereco, c.endereco)
 assert.equal(Usuario.deJSON({id:2,nome:'Admin Teste',email:'admin@example.com',perfil:'ADM',nivelPermissao:'total'}).nivelPermissao,'total')
})
test('carrinho agrega, calcula centavos e remove', () => {
 const c = new Carrinho()
 c.adicionarItem(ItemPedido.dePrato(prato()))
 c.adicionarItem(ItemPedido.dePrato(prato(),2))
 assert.equal(c.itens.length,1)
 assert.equal(c.total,59.70)
 c.diminuirQuantidade(1)
 assert.equal(c.total,39.80)
 c.removerItem(1)
 assert.equal(c.total,0)
})
test('fluxo e serialização de pedido', () => {
 const c = new Carrinho([ItemPedido.dePrato(prato())])
 const p = Pedido.doCarrinho(c,new Cliente(1,'Ana Teste','ana@example.com','Rua Teste 123'),'')
 assert.throws(() => p.marcarPronto())
 assert.throws(() => p.iniciarPreparo(0))
 p.iniciarPreparo(20)
 p.marcarPronto()
 p.marcarEntregue()
 assert.equal(Pedido.deJSON(JSON.parse(JSON.stringify(p))).status,'Entregue')
 assert.throws(() => p.iniciarPreparo(20))
})
test('validação de cliente, prato e cozinheiro', () => {
 assert.throws(() => new CadastroCliente('Ana Teste','invalido','SenhaSegura123','Rua Teste'))
 assert.throws(() => new CadastroCliente('Ana Teste','ana@example.com','123','Rua Teste'))
 assert.throws(() => new Cozinheiro(1,'Chef Teste','chef@example.com','invalido','Massas e molhos'))
 assert.throws(() => {prato().preco=-1})
 assert.throws(() => {ItemPedido.dePrato(prato()).quantidade=1.5})
 assert.equal(JSON.parse(JSON.stringify(new Login('admin@example.com','provisoria'))).senha,'provisoria')
})
